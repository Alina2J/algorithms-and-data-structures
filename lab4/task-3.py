# Задание 3. Рекурсивное возведение в целую степень.
def power(x, n):
    # Любое число в нулевой степени принимаем равным 1.
    if n == 0:
        return 1.0
    # Отрицательная степень — единица, делённая на положительную степень.
    if n < 0:
        return 1 / power(x, -n)
    # Считаем половину степени, чтобы уменьшать задачу вдвое при каждом вызове.
    half = power(x, n // 2)
    if n % 2 == 0:
        return half * half
    # Для нечётной степени нужен ещё один множитель x.
    return half * half * x


print("=" * 60)
print("Задание 3. Возведение в степень")
print("\n--- ВВОД ДАННЫХ ---")
x = float(input("Введите основание x: "))
n = int(input("Введите целую степень n: "))

print("\n--- РЕЗУЛЬТАТ ---")
if x == 0 and n < 0:
    print("Ошибка: ноль нельзя возвести в отрицательную степень.")
else:
    print(f"{x} в степени {n}: {power(x, n)}")
print("=" * 60)
