# Задание 9. Рекурсивное решение Ханойской башни.
def hanoi(n, source, target, auxiliary):
    # Если дисков нет, переносить нечего — завершаем рекурсию.
    if n == 0:
        return
    # Сначала переносим верхние n - 1 дисков на вспомогательный стержень.
    hanoi(n - 1, source, auxiliary, target)
    # Теперь самый большой из оставшихся дисков можно перенести на целевой стержень.
    print(f"Перенести диск {n}: {source} -> {target}")
    # Переносим маленькие диски со вспомогательного стержня на целевой.
    hanoi(n - 1, auxiliary, target, source)


