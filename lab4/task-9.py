if n <= 0:
    print("Ошибка: количество дисков должно быть положительным.")
else:
    print("Переносим башню со стержня A на C, используя B.")
    print("Диск 1 — самый маленький. Ходы:")
    hanoi(n, "A", "C", "B")
    print("Количество ходов:", 2 ** n - 1)
