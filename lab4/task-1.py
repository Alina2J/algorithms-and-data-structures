# Задание 1. Рекурсивное вычисление факториала.
def factorial(n):
    # Факториал 0 и 1 равен 1. Здесь рекурсия заканчивается.
    if n <= 1:
        return 1
    # Например, 5! = 5 * 4!. Каждый вызов уменьшает число на 1.
    return n * factorial(n - 1)


print("=" * 60)
print("Задание 1. Факториал числа")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите целое неотрицательное число n: "))

print("\n--- РЕЗУЛЬТАТ ---")
if n < 0:
    print("Ошибка: n должно быть неотрицательным.")
else:
    print(f"Факториал числа {n}: {factorial(n)}")
print("=" * 60)
