print("Нумерация: F(0) = 0, F(1) = 1, F(2) = 1.")
n = int(input("Введите целый неотрицательный номер n: "))

print("\n--- РЕЗУЛЬТАТ ---")
if n < 0:
    print("Ошибка: номер должен быть неотрицательным.")
else:
    print(f"F({n}) = {fibonacci(n)}")
