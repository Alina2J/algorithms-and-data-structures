# Задание 2. Рекурсивное вычисление числа Фибоначчи.
def fibonacci(n, saved=None):
    # Создаём словарь уже найденных значений для одного запуска функции.
    if saved is None:
        saved = {0: 0, 1: 1}
    # Если ответ уже известен, возвращаем его без новых вычислений.
    if n in saved:
        return saved[n]
    # Следующее число равно сумме двух предыдущих.
    saved[n] = fibonacci(n - 1, saved) + fibonacci(n - 2, saved)
    return saved[n]


