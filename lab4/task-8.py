# Задание 8. Рекурсивный подсчёт цифр.
def count_digits(number):
    # Знак минус не является цифрой, поэтому берём модуль числа.
    number = abs(number)
    # У числа от 0 до 9 ровно одна цифра, в том числе у самого нуля.
    if number < 10:
        return 1
    # Убираем последнюю цифру делением на 10 без остатка.
    return 1 + count_digits(number // 10)


print("=" * 60)
print("Задание 8. Количество цифр в числе")
print("\n--- ВВОД ДАННЫХ ---")
number = int(input("Введите целое число: "))

print("\n--- РЕЗУЛЬТАТ ---")
print("Количество цифр:", count_digits(number))
