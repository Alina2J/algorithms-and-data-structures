# Лабораторная 10. Бинарный поиск в отсортированном массиве.
def binary_search(numbers, target):
    # Границы включают первый и последний элементы текущей области поиска.
    # Индексы Python начинаются с нуля, поэтому последний индекс равен длине минус 1.
    left = 0
    right = len(numbers) - 1
    step = 1

    # Пока границы не пересеклись, в области поиска ещё есть элементы.
    while left <= right:
        # // делит без дробной части: получаем целый индекс среднего элемента.
        middle = (left + right) // 2
        print(f"Шаг {step}: границы по индексам [{left}; {right}], "
              f"середина — индекс {middle}, значение {numbers[middle]}.")

        if numbers[middle] == target:
            return middle
        if numbers[middle] > target:
            # В отсортированном массиве справа значения не меньше среднего.
            # Искомое число может быть только слева, саму середину исключаем.
            right = middle - 1
            print("Ищем в левой половине.")
        else:
            # Если среднее значение меньше искомого, оставляем правую половину.
            left = middle + 1
            print("Ищем в правой половине.")
        step += 1

    # Область поиска стала пустой, значит искомого значения в массиве нет.
    return -1


print("=" * 60)
print("Лабораторная 10. Бинарный поиск")
print("\n--- ВВОД ДАННЫХ ---")
print("Сначала введите количество элементов, затем целые числа по возрастанию.")

# Повторяем ввод размера, пока не получим положительное целое число.
while True:
    try:
        n = int(input("Количество элементов N (> 0), одно число: "))
    except ValueError:
        print("Введите одно целое число, например 5.")
        continue
    if n <= 0:
        print("Количество элементов должно быть положительным.")
        continue
    break

while True:
    try:
        # split разбивает строку по пробелам, map(int, ...) переводит части в числа.
        numbers = list(map(int, input(f"Введите {n} целых чисел по возрастанию: ").split()))
    except ValueError:
        print("Введите только целые числа через пробел.")
        continue
    if len(numbers) != n:
        print(f"Нужно ровно {n} чисел. Сейчас введено: {len(numbers)}.")
        continue
    # Бинарный поиск работает только в упорядоченном массиве.
    # Проверяем соседей: равные значения разрешены, уменьшение — нет.
    ordered = True
    for i in range(1, n):
        if numbers[i] < numbers[i - 1]:
            ordered = False
            break
    if not ordered:
        print("Массив должен быть отсортирован по возрастанию. Повторите ввод.")
        continue
    break

while True:
    try:
        target = int(input("Введите искомое целое число: "))
        break
    except ValueError:
        print("Введите одно целое число.")

print("\n--- ХОД ПОИСКА ---")
print("Массив:", numbers)
print("Искомое число:", target)
index = binary_search(numbers, target)

print("\n--- РЕЗУЛЬТАТ ---")
if index == -1:
    print("Число не найдено. Возвращённый индекс: -1.")
else:
    print("Индекс найденного элемента (с нуля):", index)
    print("Позиция элемента (с единицы):", index + 1)
    print("Если число повторяется, найдено одно из его вхождений.")
print("=" * 60)
