# Лабораторная 12. Работа с очередью по принципу FIFO.
from collections import deque


def read_integer(prompt):
    # Повторяем запрос, если вместо целого числа ввели текст или несколько чисел.
    while True:
        try:
            return int(input(prompt))
        except ValueError:
            print("Введите одно целое число.")


def show_queue(items):
    if not items:
        print("Очередь пуста.")
    else:
        # Показываем элементы от начала к концу, не удаляя их из очереди.
        print("Начало -> " + " -> ".join(map(str, items)) + " <- Конец")


def main():
    # deque позволяет быстро добавлять элементы справа и извлекать их слева.
    # FIFO означает: кто первым добавлен, тот первым извлекается.
    items = deque()
    print("=" * 60)
    print("Лабораторная 12. Работа с очередью")
    print("Элементы — целые числа. Очередь изначально пуста.")

    # После каждой операции возвращаемся к меню. Команда 0 завершает программу.
    while True:
        print("\n--- МЕНЮ ---")
        print("1. Добавить элемент в конец")
        print("2. Извлечь элемент из начала")
        print("3. Посмотреть первый элемент без удаления")
        print("4. Показать очередь")
        print("5. Узнать размер очереди")
        print("6. Проверить, пуста ли очередь")
        print("7. Найти элемент")
        print("8. Очистить очередь")
        print("0. Выход")
        print("\n--- ВВОД ДАННЫХ ---")
        choice = read_integer("Выберите действие: ")

        # Дополнительные данные запрашиваем только для добавления и поиска.
        if choice == 1 or choice == 7:
            value = read_integer("Введите целое число: ")

        print("\n--- РЕЗУЛЬТАТ ---")
        if choice == 0:
            print("Работа с очередью завершена.")
            print("=" * 60)
            break
        elif choice == 1:
            # append ставит новый элемент после всех уже ожидающих элементов.
            items.append(value)
            print("Добавлен элемент:", value)
            show_queue(items)
        elif choice == 2:
            # Из пустой очереди извлекать нельзя: сначала проверяем наличие элементов.
            if items:
                value = items.popleft()
                print("Извлечён элемент:", value)
                show_queue(items)
            else:
                print("Очередь пуста. Извлекать нечего.")
        elif choice == 3:
            if items:
                # Индекс 0 даёт первый элемент, но оставляет его в очереди.
                print("Первый элемент:", items[0])
            else:
                print("Очередь пуста. Первого элемента нет.")
        elif choice == 4:
            show_queue(items)
        elif choice == 5:
            print("Количество элементов:", len(items))
        elif choice == 6:
            # Пустая очередь считается ложным значением, непустая — истинным.
            if not items:
                print("Очередь пуста.")
            else:
                print("Очередь не пуста.")
        elif choice == 7:
            # in проверяет наличие значения, не меняя порядок элементов.
            if value in items:
                print("Элемент найден в очереди.")
            else:
                print("Элемент не найден в очереди.")
        elif choice == 8:
            # clear удаляет все элементы сразу. После очистки очередь можно заполнить снова.
            items.clear()
            print("Очередь очищена.")
        else:
            print("Нет такого действия. Выберите пункт от 0 до 8.")
        print("=" * 60)


# При запуске файла открываем меню. При импорте функции остаются доступны отдельно.
if __name__ == "__main__":
    main()
