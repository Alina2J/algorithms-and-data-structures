# Лабораторная 8. Сортировка вставками по возрастанию.
def insertion_sort(numbers):
    # Создаём копию списка, чтобы сохранить исходный массив без изменений.
    result = numbers.copy()

    # Первый элемент уже образует отсортированную часть из одного числа.
    # Начинаем со второго и постепенно расширяем эту часть вправо.
    for i in range(1, len(result)):
        # Сохраняем вставляемое число: при сдвигах его место может быть перезаписано.
        current = result[i]
        j = i - 1

        # Двигаемся по отсортированной части справа налево.
        # Все числа больше current сдвигаем на одну позицию вправо.
        # Сначала проверяем j >= 0, чтобы не выйти за левую границу этой части.
        while j >= 0 and result[j] > current:
            result[j + 1] = result[j]
            j -= 1

        # После цикла j указывает на число не больше current или равен -1.
        # В обоих случаях нужное место для вставки — следующая позиция j + 1.
        # Равные числа не сдвигаем, поэтому их взаимный порядок сохраняется.
        result[j + 1] = current
        print(f"Шаг {i}: вставили {current} на позицию {j + 2}:", result)

    return result


