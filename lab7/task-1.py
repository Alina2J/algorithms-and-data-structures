# Лабораторная 7. Сортировка пузырьком по возрастанию.
def bubble_sort(numbers):
    # Работаем с копией, чтобы исходный массив можно было вывести отдельно.
    result = numbers.copy()
    n = len(result)

    # После каждого прохода наибольший из оставшихся элементов оказывается справа.
    # Поэтому правую границу проверки каждый раз уменьшаем на одну позицию.
    for end in range(n - 1, 0, -1):
        swapped = False
        for j in range(end):
            # Сравниваем соседей. Если левый больше правого, меняем их местами.
            # Равные элементы не переставляем: их взаимный порядок сохраняется.
            if result[j] > result[j + 1]:
                result[j], result[j + 1] = result[j + 1], result[j]
                swapped = True

        print(f"После прохода {n - end}:", result)
        # Если обменов не было, все соседи уже стоят правильно — завершаем сортировку.
        if not swapped:
            print("Обменов не было: массив уже отсортирован.")
            break

    return result


print("=" * 60)
print("Лабораторная 7. Сортировка пузырьком")
