print("Сначала введите количество элементов, затем сами целые числа.")

# Повторяем ввод размера, пока пользователь не введёт положительное целое число.
while True:
    try:
        n = int(input("Количество элементов N (> 0), одно число: "))
    except ValueError:
        print("Введите одно целое число, например 5.")
        continue
    if n <= 0:
        print("Количество элементов должно быть положительным.")
        continue
    break

while True:
    try:
        # split разделяет строку по пробелам, map(int, ...) переводит части в числа.
        numbers = list(map(int, input(f"Введите {n} целых чисел через пробел: ").split()))
    except ValueError:
        print("Введите только целые числа через пробел. Повторения допускаются.")
        continue
    if len(numbers) != n:
        print(f"Нужно ровно {n} чисел. Сейчас введено: {len(numbers)}.")
        continue
    break

print("\n--- ХОД СОРТИРОВКИ ---")
print("Исходный массив:", numbers)
sorted_numbers = bubble_sort(numbers)

print("\n--- РЕЗУЛЬТАТ ---")
print("Массив по возрастанию:", sorted_numbers)
print("=" * 60)
