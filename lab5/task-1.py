# Задание 1. Первые N положительных нечётных чисел.
print("=" * 60)
print("Задание 1. Массив нечётных чисел")
print("\n--- ВВОД ДАННЫХ ---")
# N задаёт количество элементов. int превращает введённый текст в целое число.
n = int(input("Введите размер массива N (> 0): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0:
    print("Ошибка: N должно быть положительным.")
else:
    # Создаём пустой список и постепенно заполняем его числами.
    numbers = []
    # range(n) даёт N значений: от 0 до N - 1.
    # Формула 2 * i + 1 даёт нечётные числа 1, 3, 5 и далее.
    for i in range(n):
        # append добавляет найденное число в конец списка.
        numbers.append(2 * i + 1)
    print("Массив:", numbers)
print("=" * 60)
