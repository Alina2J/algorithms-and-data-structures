# Задание 2. Массив членов геометрической прогрессии.
print("=" * 60)
print("Задание 2. Геометрическая прогрессия")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (> 1): "))
# A — начальное значение, D — число, на которое умножаем каждый следующий член.
# float позволяет вводить дробные значения, например 1.5.
a = float(input("Введите первый член A: "))
d = float(input("Введите знаменатель D: "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 1:
    print("Ошибка: N должно быть больше 1.")
else:
    numbers = []
    current = a
    # За N повторений записываем N членов прогрессии.
    # current хранит очередной член: A, затем A * D, затем A * D * D и так далее.
    for i in range(n):
        numbers.append(current)
        current = current * d
    print("Массив:", numbers)
print("=" * 60)
