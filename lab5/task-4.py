# Задание 4. Вывод элементов по очереди с начала и с конца.
print("=" * 60)
print("Задание 4. Элементы с двух концов массива")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (> 0): "))
# split разбивает ввод по пробелам, map(float, ...) переводит части в числа,
# а list собирает полученные значения в список.
numbers = list(map(float, input("Введите элементы через пробел: ").split()))

print("\n--- РЕЗУЛЬТАТ ---")
# len показывает количество введённых элементов: оно должно совпадать с N.
if n <= 0 or len(numbers) != n:
    print("Ошибка: N должно быть положительным, нужно ввести ровно N элементов.")
else:
    result = []
    # Индексы начинаются с нуля: первый элемент — 0, последний — N - 1.
    left = 0
    right = n - 1
    # Пока границы не пересеклись, берём элемент слева, затем справа.
    # После каждой пары сдвигаем обе границы к середине массива.
    while left <= right:
        result.append(numbers[left])
        # Центральный элемент при нечётном N добавляем только один раз.
        if left != right:
            result.append(numbers[right])
        left = left + 1
        right = right - 1
    print("Элементы в нужном порядке:", result)
print("=" * 60)
