# Задание 9. Номер последнего локального максимума.
print("=" * 60)
print("Задание 9. Последний локальный максимум")
print("\n--- ВВОД ДАННЫХ ---")
print("Крайний элемент сравнивается с одним соседом, остальные — с двумя.")
n = int(input("Введите размер массива N (не меньше 2): "))
numbers = list(map(float, input("Введите элементы через пробел: ").split()))

print("\n--- РЕЗУЛЬТАТ ---")
if n < 2 or len(numbers) != n:
    print("Ошибка: нужны как минимум два элемента и ровно N чисел.")
else:
    # Номера начинаются с 1, поэтому 0 используем как признак «максимум не найден».
    last_maximum = 0
    # Идём справа налево: первый найденный максимум будет последним по номеру.
    for i in range(n - 1, -1, -1):
        # На краю один сосед отсутствует, поэтому проверку с этой стороны пропускаем.
        # or не вычисляет вторую часть, если первая уже истинна: за границы не выходим.
        greater_left = i == 0 or numbers[i] > numbers[i - 1]
        greater_right = i == n - 1 or numbers[i] > numbers[i + 1]
        # Элемент должен быть строго больше каждого имеющегося соседа.
        if greater_left and greater_right:
            # Превращаем индекс Python в номер из условия и прекращаем поиск.
            last_maximum = i + 1
            break
    if last_maximum == 0:
        print("Локальных максимумов нет.")
    else:
        print("Номер последнего локального максимума:", last_maximum)
        print("Его значение:", numbers[last_maximum - 1])
print("=" * 60)
