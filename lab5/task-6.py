# Задание 6. Среднее арифметическое на участке массива.
print("=" * 60)
print("Задание 6. Среднее элементов с номерами от K до L")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (> 0): "))
numbers = list(map(float, input("Введите элементы через пробел: ").split()))
# K и L — номера первого и последнего элементов выбранного участка, включая оба.
k = int(input("Введите начальный номер K (с единицы): "))
l = int(input("Введите конечный номер L (с единицы): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0 or len(numbers) != n:
    print("Ошибка: N должно быть положительным, нужно ввести ровно N элементов.")
# Границы должны идти по порядку и не выходить за пределы массива.
elif not 1 <= k <= l <= n:
    print("Ошибка: должно выполняться условие 1 <= K <= L <= N.")
else:
    total = 0.0
    # Номеру K соответствует индекс K - 1, номеру L — индекс L - 1.
    # range не включает правую границу, поэтому указываем L, чтобы учесть последний элемент.
    for i in range(k - 1, l):
        total = total + numbers[i]
    # Делим сумму на количество выбранных элементов. +1 учитывает обе границы.
    average = total / (l - k + 1)
    print("Среднее арифметическое:", average)
print("=" * 60)
