# Задание 5. Сначала нечётные номера, затем чётные в обратном порядке.
print("=" * 60)
print("Задание 5. Порядок элементов по их номерам")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (> 0): "))
# Разбиваем строку по пробелам и сохраняем введённые числа в список.
numbers = list(map(float, input("Введите элементы через пробел: ").split()))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0 or len(numbers) != n:
    print("Ошибка: N должно быть положительным, нужно ввести ровно N элементов.")
else:
    # Собираем нужный порядок в отдельном списке, исходный массив не меняем.
    result = []
    # Номерам 1, 3, 5 соответствуют индексы 0, 2, 4: индексы Python начинаются с 0.
    for i in range(0, n, 2):
        result.append(numbers[i])
    # range с шагом -1 перебирает индексы от последнего до нулевого.
    # Проверяем номер i + 1, а не значение элемента: нужны именно чётные позиции.
    for i in range(n - 1, -1, -1):
        if (i + 1) % 2 == 0:
            result.append(numbers[i])
    print("Элементы в нужном порядке:", result)
print("=" * 60)
