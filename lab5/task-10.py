# Задание 10. Номера двух одинаковых элементов.
print("=" * 60)
print("Задание 10. Поиск одинаковых элементов")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (не меньше 2): "))
numbers = list(map(int, input("Введите целые числа с ровно одной парой одинаковых: ").split()))

print("\n--- РЕЗУЛЬТАТ ---")
if n < 2 or len(numbers) != n:
    print("Ошибка: нужны как минимум два элемента и ровно N чисел.")
else:
    # Словарь связывает значение элемента с номером его первого появления.
    # Например, запись 7: 2 означает, что число 7 впервые встретилось на позиции 2.
    first_positions = {}
    pairs = []
    for i in range(n):
        value = numbers[i]
        # Если значение уже есть в словаре, сохраняем номера первого и текущего вхождений.
        if value in first_positions:
            pairs.append((first_positions[value], i + 1))
        else:
            # При первом появлении запоминаем номер i + 1, поскольку индексы идут с нуля.
            first_positions[value] = i + 1
    # Единственный повтор означает, что ровно одно число встретилось два раза.
    # Три одинаковых элемента или две разные пары дадут больше одной записи в pairs.
    if len(pairs) != 1:
        print("Ошибка: массив должен содержать ровно одну пару одинаковых элементов.")
    else:
        # Перебирали слева направо, поэтому первый номер уже меньше второго.
        first, second = pairs[0]
        print("Номера одинаковых элементов:", first, second)
        print("Повторяющееся значение:", numbers[first - 1])
print("=" * 60)
