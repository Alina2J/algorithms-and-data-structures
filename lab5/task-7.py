# Задание 7. Проверка арифметической прогрессии.
print("=" * 60)
print("Задание 7. Арифметическая прогрессия")
print("\n--- ВВОД ДАННЫХ ---")
print("Сначала введите количество элементов одним числом, затем сами элементы.")
print("Пример: количество — 3, элементы — 2 3 4.")
# while True повторяет ввод, пока не дойдём до break после всех проверок.
# try/except перехватывает ValueError: например, если вместо числа ввели «2 3 4».
while True:
    try:
        n = int(input("Сколько элементов в массиве? Введите одно целое число N >= 2: "))
    except ValueError:
        print("Нужно одно целое число, например 3. Элементы вводятся на следующем шаге.")
        # continue возвращает нас к началу цикла, чтобы снова запросить N.
        continue
    if n < 2:
        print("В массиве должно быть хотя бы два элемента.")
        continue
    break

# Отдельно проверяем сами элементы: их должно быть ровно N, без повторений.
while True:
    try:
        numbers = list(map(int, input(f"Введите {n} разных целых чисел через пробел: ").split()))
    except ValueError:
        print("Используйте только целые числа, разделённые пробелами.")
        continue
    if len(numbers) != n:
        print(f"Нужно ввести ровно {n} чисел. Сейчас введено: {len(numbers)}.")
        continue
    # set оставляет только уникальные значения. Если их меньше N, есть повторы.
    if len(set(numbers)) != n:
        print("По условию все числа должны быть различными. Повторите ввод.")
        continue
    break

print("\n--- РЕЗУЛЬТАТ ---")
if n < 2 or len(numbers) != n:
    print("Ошибка: нужны как минимум два элемента и ровно N чисел.")
elif len(set(numbers)) != n:
    print("Ошибка: по условию все числа должны быть различными.")
else:
    # Разность первых двух элементов берём за образец для остальных пар.
    # Например, в массиве 2, 5, 8 все соседние элементы отличаются на 3.
    difference = numbers[1] - numbers[0]
    # Сначала предполагаем, что прогрессия есть. Одного несовпадения достаточно для отказа.
    is_progression = True
    for i in range(2, n):
        if numbers[i] - numbers[i - 1] != difference:
            is_progression = False
            # Дальнейшая проверка не нужна: постоянной разности уже нет.
            break
    if is_progression:
        print("Разность арифметической прогрессии:", difference)
    else:
        print("Массив не образует арифметическую прогрессию. Ответ: 0")
print("=" * 60)
