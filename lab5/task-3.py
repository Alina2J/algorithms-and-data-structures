# Задание 3. Каждый новый элемент равен сумме предыдущих.
print("=" * 60)
print("Задание 3. Массив из сумм предыдущих элементов")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (> 2): "))
a = int(input("Введите первый элемент A: "))
b = int(input("Введите второй элемент B: "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 2:
    print("Ошибка: N должно быть больше 2.")
else:
    # Первые два элемента заданы пользователем, поэтому сразу помещаем их в список.
    numbers = [a, b]
    total = a + b
    # total хранит сумму всех уже добавленных элементов — это значение следующего.
    # Первые два элемента готовы, поэтому цикл добавляет оставшиеся N - 2 элемента.
    for i in range(2, n):
        numbers.append(total)
        # Индекс -1 означает последний элемент. Учитываем его в сумме для нового шага.
        total = total + numbers[-1]
    print("Массив:", numbers)
print("=" * 60)
