# Задание 8. Минимум среди элементов с чётными номерами.
print("=" * 60)
print("Задание 8. Минимум элементов с чётными номерами")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите размер массива N (не меньше 2): "))
# Вводим весь массив одной строкой. float допускает дробные элементы.
numbers = list(map(float, input("Введите элементы через пробел: ").split()))

print("\n--- РЕЗУЛЬТАТ ---")
if n < 2 or len(numbers) != n:
    print("Ошибка: нужны как минимум два элемента и ровно N чисел.")
else:
    # Проверяем позиции 2, 4, 6, а не чётность самих значений.
    # Второй элемент имеет индекс 1. Берём его за начальный минимум.
    minimum = numbers[1]
    # Второй элемент уже учтён. Шаг 2 позволяет проверить позиции 4, 6, 8 и далее.
    for i in range(3, n, 2):
        if numbers[i] < minimum:
            # Если нашли меньшее значение, запоминаем его вместо предыдущего минимума.
            minimum = numbers[i]
    print("Минимальный элемент с чётным номером:", minimum)
print("=" * 60)
