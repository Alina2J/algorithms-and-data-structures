# Задание 5. Описание целого числа.
print("=" * 60)
print("Задание 5. Описание целого числа")
print("\n--- ВВОД ДАННЫХ ---")
number = int(input("Введите целое число: "))

print("\n--- РЕЗУЛЬТАТ ---")
if number == 0:
    print("Нулевое число")
else:
    # Сначала определяем знак числа.
    if number > 0:
        sign = "Положительное"
    else:
        sign = "Отрицательное"

    # % даёт остаток от деления. У чётного числа остаток от деления на 2 равен 0.
    if number % 2 == 0:
        parity = "четное"
    else:
        parity = "нечетное"
    print(sign, parity, "число")
print("=" * 60)
