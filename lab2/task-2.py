# float позволяет вводить и целые, и дробные числа.
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
c = float(input("Введите третье число: "))

# Находим самое маленькое число и складываем два остальных.
if a <= b and a <= c:
    result = b + c
elif b <= a and b <= c:
    result = a + c
else:
    result = a + b

print("\n--- РЕЗУЛЬТАТ ---")
print("Сумма двух наибольших чисел:", result)
