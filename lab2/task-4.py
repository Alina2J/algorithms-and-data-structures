# Задание 4. Координатная четверть точки.
print("=" * 60)
print("Задание 4. Координатная четверть точки")
print("\n--- ВВОД ДАННЫХ ---")
x = float(input("Введите x: "))
y = float(input("Введите y: "))

print("\n--- РЕЗУЛЬТАТ ---")
# На осях хотя бы одна координата равна нулю — четверти у такой точки нет.
if x == 0 or y == 0:
    print("Точка лежит на координатной оси и не относится к четвертям.")
elif x > 0 and y > 0:
    print("Номер четверти: 1")
elif x < 0 and y > 0:
    print("Номер четверти: 2")
elif x < 0 and y < 0:
    print("Номер четверти: 3")
else:
    print("Номер четверти: 4")
print("=" * 60)
