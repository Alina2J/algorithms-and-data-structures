# Задание 6. Чётность и количество цифр числа.
print("=" * 60)
print("Задание 6. Чётность и количество цифр числа")
print("\n--- ВВОД ДАННЫХ ---")
number = int(input("Введите целое число от 1 до 999: "))

print("\n--- РЕЗУЛЬТАТ ---")
if number < 1 or number > 999:
    print("Ошибка: число должно быть от 1 до 999.")
else:
    # Проверяем остаток от деления на 2, чтобы определить чётность.
    if number % 2 == 0:
        parity = "Четное"
    else:
        parity = "Нечетное"

    # До 10 — одна цифра, до 100 — две, дальше — три.
    if number < 10:
        digits = "однозначное"
    elif number < 100:
        digits = "двузначное"
    else:
        digits = "трехзначное"
    print(parity, digits, "число")
print("=" * 60)
