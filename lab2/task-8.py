# Задание 8. Количество учебных заданий словами.
print("=" * 60)
print("Задание 8. Количество учебных заданий словами")
print("\n--- ВВОД ДАННЫХ ---")
number = int(input("Введите количество заданий от 10 до 40: "))

teens = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")
units = ("", "одно", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")

print("\n--- РЕЗУЛЬТАТ ---")
if number < 10 or number > 40:
    print("Ошибка: количество должно быть от 10 до 40.")
else:
    # Числа от 10 до 19 имеют особые названия и одно общее окончание.
    if number < 20:
        text = teens[number - 10]
        ending = "учебных заданий"
    else:
        if number < 30:
            text = "двадцать"
        elif number < 40:
            text = "тридцать"
        else:
            text = "сорок"

        # Последняя цифра определяет добавочное слово и окончание.
        last_digit = number % 10
        if last_digit != 0:
            text = text + " " + units[last_digit]
        if last_digit == 1:
            ending = "учебное задание"
        elif 2 <= last_digit <= 4:
            ending = "учебных задания"
        else:
            ending = "учебных заданий"
    print(text, ending)
print("=" * 60)
