# Задание 10. Название года в восточном календаре.
print("=" * 60)
print("Задание 10. Название года в восточном календаре")
print("\n--- ВВОД ДАННЫХ ---")
year = int(input("Введите номер года (положительное целое число): "))

animals = ("крысы", "коровы", "тигра", "зайца", "дракона", "змеи",
           "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи")

print("\n--- РЕЗУЛЬТАТ ---")
if year < 1:
    print("Ошибка: номер года должен быть положительным.")
else:
    # Остаток от деления на 60 даёт положение года в цикле, начиная с 1984.
    cycle_year = (year - 1984) % 60
    animal_index = cycle_year % 12
    color_index = cycle_year // 12

    # Цвет меняется после каждого подцикла из 12 лет.
    # У тигра, зайца и дракона название мужского рода, у остальных — женского.
    if animal_index == 2 or animal_index == 3 or animal_index == 4:
        colors = ("зеленого", "красного", "желтого", "белого", "черного")
    else:
        colors = ("зеленой", "красной", "желтой", "белой", "черной")
    print("Год", colors[color_index], animals[animal_index])
print("=" * 60)
