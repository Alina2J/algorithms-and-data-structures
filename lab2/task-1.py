print("\n--- ВВОД ДАННЫХ ---")
# int переводит введённый текст в целое число.
a = int(input("Введите A: "))
b = int(input("Введите B: "))

# Если числа разные, сохраняем большее в обе переменные.
if a > b:
    b = a
elif b > a:
    a = b
else:
    # Если числа одинаковые, заменяем оба числа нулями.
    a = 0
    b = 0

print("\n--- РЕЗУЛЬТАТ ---")
print("Новое значение A:", a)
print("Новое значение B:", b)
print("=" * 60)
