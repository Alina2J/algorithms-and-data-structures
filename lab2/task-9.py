# Задание 9. Трёхзначное число словами.
print("=" * 60)
print("Задание 9. Трёхзначное число словами")
print("\n--- ВВОД ДАННЫХ ---")
number = int(input("Введите целое число от 100 до 999: "))

hundreds = ("", "сто", "двести", "триста", "четыреста", "пятьсот",
            "шестьсот", "семьсот", "восемьсот", "девятьсот")
tens = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят",
        "шестьдесят", "семьдесят", "восемьдесят", "девяносто")
teens = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")
units = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")

print("\n--- РЕЗУЛЬТАТ ---")
if number < 100 or number > 999:
    print("Ошибка: число должно быть от 100 до 999.")
else:
    # // делит без дробной части, % находит остаток от деления.
    text = hundreds[number // 100]
    remainder = number % 100
    if 10 <= remainder <= 19:
        # Названия от 10 до 19 берём целиком.
        text = text + " " + teens[remainder - 10]
    else:
        # Для остальных чисел отдельно добавляем десятки и единицы.
        if remainder >= 20:
            text = text + " " + tens[remainder // 10]
        if remainder % 10 != 0:
            text = text + " " + units[remainder % 10]
    print(text)
print("=" * 60)
