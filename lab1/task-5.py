# Задание 5. Операции с модулями двух ненулевых чисел
print("=" * 60)
print('Задание 5. Операции с модулями двух ненулевых чисел.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим два ненулевых числа, чтобы при делении не получить деление на ноль
a = float(input("Введите ненулевое число a: "))
b = float(input("Введите ненулевое число b: "))

# abs находит модуль числа: отрицательное число становится положительным
a_abs = abs(a)
b_abs = abs(b)

# Складываем, вычитаем, умножаем и делим модули чисел, выводим ответы
print("\n--- РЕЗУЛЬТАТ ---")
print("Сумма модулей:", a_abs + b_abs)
print("Разность модулей:", a_abs - b_abs)
print("Произведение модулей:", a_abs * b_abs)
print("Частное модулей:", a_abs / b_abs)
print("=" * 60)
