# Вводим два числа
a = float(input("Введите число a: "))
b = float(input("Введите число b: "))

# Складываем числа и делим сумму на два — получаем среднее арифметическое
average = (a + b) / 2

# Выводим среднее арифметическое.
print("\n--- РЕЗУЛЬТАТ ---")
print("Среднее арифметическое:", average)
