# Задание 7. Длины отрезков AC, BC и их сумма
print("=" * 60)
print('Задание 7. Длины отрезков AC, BC и их сумма.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим положения трёх точек на числовой прямой
a = float(input("Введите координату A: "))
b = float(input("Введите координату B: "))
c = float(input("Введите координату C: "))

# Длина отрезка — модуль разности координат: длина не бывает отрицательной
ac = abs(c - a)
bc = abs(c - b)

# Выводим длины обоих отрезков и их сумму
print("\n--- РЕЗУЛЬТАТ ---")
print("Длина AC:", ac)
print("Длина BC:", bc)
print("Сумма длин:", ac + bc)
print("=" * 60)
