# Вводим диаметр окружности
d = float(input("Введите диаметр: "))
# Берём приближённое значение числа пи
pi = 3.14

# Чтобы найти длину окружности, умножаем число пи на диаметр
length = pi * d

# Выводим длину окружности
print("\n--- РЕЗУЛЬТАТ ---")
print("Длина окружности:", length)
print("=" * 60)
