# Задание 6. Расстояние между двумя точками на плоскости
# Подключаем sqrt — функцию для вычисления квадратного корня
from math import sqrt

print("=" * 60)
print('Задание 6. Расстояние между двумя точками на плоскости.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим координаты x и y сначала первой точки, затем второй
x1 = float(input("Введите x1: "))
y1 = float(input("Введите y1: "))
x2 = float(input("Введите x2: "))
y2 = float(input("Введите y2: "))

# По теореме Пифагора: складываем квадраты разностей координат и берём корень
distance = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)

# Выводим расстояние между точками
print("\n--- РЕЗУЛЬТАТ ---")
print("Расстояние между точками:", distance)
print("=" * 60)
