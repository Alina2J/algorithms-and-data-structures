# Задание 4. Операции с квадратами двух ненулевых чисел
print("=" * 60)
print('Задание 4. Операции с квадратами двух ненулевых чисел.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим два ненулевых числа, чтобы при делении не получить деление на ноль
a = float(input("Введите ненулевое число a: "))
b = float(input("Введите ненулевое число b: "))

# Возводим каждое число в квадрат: ** 2 означает умножение числа на себя
a_squared = a ** 2
b_squared = b ** 2

# Складываем, вычитаем, умножаем и делим квадраты чисел, выводим ответы
print("\n--- РЕЗУЛЬТАТ ---")
print("Сумма квадратов:", a_squared + b_squared)
print("Разность квадратов:", a_squared - b_squared)
print("Произведение квадратов:", a_squared * b_squared)
print("Частное квадратов:", a_squared / b_squared)
print("=" * 60)
