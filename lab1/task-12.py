# Задание 12. Значение функции y = 4*(x-3)^6 - 7*(x-3)^3 + 2
print("=" * 60)
print('Задание 12. Значение функции y = 4*(x-3)^6 - 7*(x-3)^3 + 2.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим значение x, для которого нужно посчитать функцию
x = float(input("Введите x: "))

# Сохраняем x - 3 в переменную t, чтобы не повторять это выражение в формуле
t = x - 3
# Подставляем t в формулу. ** означает возведение в степень
y = 4 * t ** 6 - 7 * t ** 3 + 2

# Выводим полученное значение функции
print("\n--- РЕЗУЛЬТАТ ---")
print("Значение y:", y)
print("=" * 60)
