# Задание 11. Значение функции y = 3*x^6 - 6*x^2 - 7
print("=" * 60)
print('Задание 11. Значение функции y = 3*x^6 - 6*x^2 - 7.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим значение x, для которого нужно посчитать функцию
x = float(input("Введите x: "))

# Подставляем x в формулу. ** 6 и ** 2 означают шестую и вторую степени
y = 3 * x ** 6 - 6 * x ** 2 - 7

# Выводим полученное значение функции
print("\n--- РЕЗУЛЬТАТ ---")
print("Значение y:", y)
print("=" * 60)
