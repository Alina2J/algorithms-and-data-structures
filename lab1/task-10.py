# Задание 10. Периметр и площадь треугольника по трем вершинам
# Подключаем sqrt — функцию для вычисления квадратного корня
from math import sqrt

print("=" * 60)
print('Задание 10. Периметр и площадь треугольника по трем вершинам.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим координаты x и y каждой из трёх вершин треугольника
x1 = float(input("Введите x1: "))
y1 = float(input("Введите y1: "))
x2 = float(input("Введите x2: "))
y2 = float(input("Введите y2: "))
x3 = float(input("Введите x3: "))
y3 = float(input("Введите y3: "))

# Находим длины трёх сторон по расстоянию между соответствующими вершинами
a = sqrt((x2 - x1) ** 2 + (y2 - y1) ** 2)
b = sqrt((x3 - x2) ** 2 + (y3 - y2) ** 2)
c = sqrt((x1 - x3) ** 2 + (y1 - y3) ** 2)
# Складываем длины всех сторон — получаем периметр
p = a + b + c

# Считаем площадь по координатам вершин. abs делает результат неотрицательным
s = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2

# Выводим периметр и площадь треугольника
print("\n--- РЕЗУЛЬТАТ ---")
print("Периметр:", p)
print("Площадь:", s)
print("=" * 60)
