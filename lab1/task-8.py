# Задание 8. Произведение длин AC и BC; C находится между A и B
print("=" * 60)
print('Задание 8. Произведение длин AC и BC; C находится между A и B.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим положения точек на прямой. По условию C должна быть между A и B
a = float(input("Введите координату A: "))
b = float(input("Введите координату B: "))
c = float(input("Введите координату C между A и B: "))

# Находим длины отрезков. abs убирает минус у разности координат
ac = abs(c - a)
bc = abs(c - b)

# Умножаем длины отрезков и выводим ответ
print("\n--- РЕЗУЛЬТАТ ---")
print("Произведение длин AC и BC:", ac * bc)
print("=" * 60)
