# Задание 9. Прямоугольник по противоположным вершинам
print("=" * 60)
print('Задание 9. Прямоугольник по противоположным вершинам.')
print("=" * 60)
print("\n--- ВВОД ДАННЫХ ---")
# Вводим координаты двух противоположных вершин прямоугольника
x1 = float(input("Введите x1: "))
y1 = float(input("Введите y1: "))
x2 = float(input("Введите x2: "))
y2 = float(input("Введите y2: "))

# Стороны идут вдоль осей: их длины — модули разностей координат x и y
a = abs(x2 - x1)
b = abs(y2 - y1)
# Периметр — сумма всех сторон, площадь — произведение двух соседних сторон
p = 2 * (a + b)
s = a * b

# Выводим периметр и площадь
print("\n--- РЕЗУЛЬТАТ ---")
print("Периметр:", p)
print("Площадь:", s)
print("=" * 60)
