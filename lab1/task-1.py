# Вводим две стороны прямоугольника. float позволяет вводить дробные числа
a = float(input("Введите сторону a: "))
b = float(input("Введите сторону b: "))

# Площадь — произведение сторон, периметр — сумма всех четырёх сторон
s = a * b
p = 2 * (a + b)

# Выводим полученные площадь и периметр
print("\n--- РЕЗУЛЬТАТ ---")
print("Площадь:", s)
print("Периметр:", p)
print("=" * 60)
