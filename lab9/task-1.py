# Лабораторная 9. Сортировка выбором по возрастанию.
def selection_sort(numbers):
    # Сортируем копию, чтобы исходный массив остался без изменений.
    result = numbers.copy()
    n = len(result)

    # Слева от позиции i уже стоят наименьшие элементы в правильном порядке.
    # На каждом шаге выбираем минимум из оставшейся правой части.
    for i in range(n - 1):
        min_index = i
        # Сначала считаем текущий элемент минимальным и сравниваем с остальными.
        # Запоминаем индекс минимума, чтобы после поиска выполнить один обмен.
        for j in range(i + 1, n):
            if result[j] < result[min_index]:
                min_index = j

        # Минимум переносим в начало неотсортированной части.
        # Если он уже на нужном месте, обмен не требуется.
        if min_index != i:
            result[i], result[min_index] = result[min_index], result[i]
            print(f"Шаг {i + 1}: минимум {result[i]}, обмен позиций {i + 1} и {min_index + 1}:", result)
        else:
            print(f"Шаг {i + 1}: минимум {result[i]} уже на позиции {i + 1}:", result)

    # После N - 1 шагов последний элемент тоже находится на своём месте.
    return result


print("=" * 60)
print("Лабораторная 9. Сортировка выбором")
print("\n--- ВВОД ДАННЫХ ---")
print("Сначала введите количество элементов, затем сами целые числа.")

# Повторяем ввод размера, пока пользователь не введёт положительное целое число.
while True:
    try:
        n = int(input("Количество элементов N (> 0), одно число: "))
    except ValueError:
        print("Введите одно целое число, например 5.")
        continue
    if n <= 0:
        print("Количество элементов должно быть положительным.")
        continue
    break

while True:
    try:
        # split разделяет строку по пробелам, map(int, ...) переводит части в числа.
        numbers = list(map(int, input(f"Введите {n} целых чисел через пробел: ").split()))
    except ValueError:
        print("Введите только целые числа через пробел. Повторения допускаются.")
        continue
    # Количество введённых чисел должно совпадать с указанным размером массива.
    if len(numbers) != n:
        print(f"Нужно ровно {n} чисел. Сейчас введено: {len(numbers)}.")
        continue
    break

print("\n--- ХОД СОРТИРОВКИ ---")
print("Исходный массив:", numbers)
print("Позиции в шагах считаются с единицы.")
sorted_numbers = selection_sort(numbers)

print("\n--- РЕЗУЛЬТАТ ---")
print("Массив по возрастанию:", sorted_numbers)
print("=" * 60)
