# Задание 5. Сумма степеней с чередованием знаков, без условного оператора.
print("=" * 60)
print("Задание 5. Сумма 1 - A + A^2 - A^3 + ...")
print("\n--- ВВОД ДАННЫХ ---")
a = float(input("Введите число A: "))
# По условию N должно быть положительным. Вводим число с учётом этого требования.
n = int(input("Введите целое число N (> 0): "))

term = 1.0
total = 1.0
# Умножение на -A одновременно даёт следующую степень и меняет знак слагаемого.
# Поэтому достаточно одного цикла, а проверка знака через if не нужна.
for i in range(1, n + 1):
    term = term * (-a)
    total = total + term

print("\n--- РЕЗУЛЬТАТ ---")
print("Значение выражения:", total)
print("=" * 60)
