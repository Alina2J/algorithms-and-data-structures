# Задание 1. Стоимость конфет разного веса.
print("=" * 60)
print("Задание 1. Стоимость конфет разного веса")
print("\n--- ВВОД ДАННЫХ ---")
price = float(input("Введите цену 1 кг конфет в рублях: "))

print("\n--- РЕЗУЛЬТАТ ---")
if price <= 0:
    print("Ошибка: цена должна быть положительной.")
else:
    print("Вес, кг | Стоимость, руб.")
    # Перебираем числа от 1 до 10 и делим на 10, получая вес от 0.1 до 1 кг.
    for i in range(1, 11):
        weight = i / 10
        cost = price * weight
        print(f"{weight:7.1f} | {cost:.2f}")
print("=" * 60)
