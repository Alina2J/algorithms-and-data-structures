# Задание 9. Рост банковского вклада.
print("=" * 60)
print("Задание 9. Рост вклада с 1000 до суммы больше 1100 руб.")
print("\n--- ВВОД ДАННЫХ ---")
p = float(input("Введите ежемесячный процент P (0 < P < 25): "))

print("\n--- РЕЗУЛЬТАТ ---")
if p <= 0 or p >= 25:
    print("Ошибка: процент должен быть больше 0 и меньше 25.")
else:
    s = 1000.0
    k = 0
    # Каждый месяц проценты начисляются на текущую сумму, включая прошлые проценты.
    # Если сумма ровно 1100, нужен ещё один месяц: требуется превысить 1100.
    while s <= 1100:
        s = s + s * p / 100
        k = k + 1
    print("Количество месяцев K:", k)
    # Округляем только вывод до копеек, сами вычисления выполняем без округления.
    print(f"Итоговый размер вклада S: {s:.2f} руб.")
print("=" * 60)
