# Задание 10. Наибольший общий делитель по алгоритму Евклида.
print("=" * 60)
print("Задание 10. Наибольший общий делитель")
print("\n--- ВВОД ДАННЫХ ---")
a = int(input("Введите положительное целое число A: "))
b = int(input("Введите положительное целое число B: "))

print("\n--- РЕЗУЛЬТАТ ---")
if a <= 0 or b <= 0:
    print("Ошибка: оба числа должны быть положительными.")
else:
    # Работаем с копиями, чтобы сохранить исходные числа для вывода.
    x = a
    y = b
    # Заменяем пару чисел вторым числом и остатком от деления первого на второе.
    while y != 0:
        remainder = x % y
        x = y
        y = remainder
    # Когда остаток стал нулём, в x находится НОД исходных чисел.
    print(f"НОД чисел {a} и {b}: {x}")
print("=" * 60)
