print("Задание 6. Повторение чисел от A до B")
print("\n--- ВВОД ДАННЫХ ---")
a = int(input("Введите положительное целое число A: "))
b = int(input("Введите положительное целое число B (B > A): "))

print("\n--- РЕЗУЛЬТАТ ---")
if a <= 0 or b <= a:
    print("Ошибка: должны выполняться условия 0 < A < B.")
else:
    # Внешний цикл выбирает очередное число от A до B включительно.
    for number in range(a, b + 1):
        # Внутренний цикл печатает это число столько раз, каково его значение.
        for repeat in range(number):
            print(number, end=" ")
        # После всех повторений одного числа переходим на новую строку.
        print()
print("=" * 60)
