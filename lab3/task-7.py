# Задание 7. Незанятая часть отрезка.
from decimal import Decimal

print("============================================================")
print("Задание 7. Незанятая часть отрезка")
print("\n--- ВВОД ДАННЫХ ---")
# Decimal хранит десятичные числа без обычной погрешности float для 0.1 и 0.3.
a = Decimal(input("Введите длину A: "))
b = Decimal(input("Введите длину B (0 < B < A): "))

print("\n--- РЕЗУЛЬТАТ ---")
if b <= 0 or a <= b:
    print("Ошибка: должны выполняться условия 0 < B < A.")
else:
    remainder = a
    # Убираем по одному отрезку B, пока оставшаяся часть не станет меньше B.
    # Для вычисления используем только вычитание, без умножения и деления.
    while remainder >= b:
        remainder = remainder - b
    print("Длина незанятой части:", remainder)
print("============================================================")
