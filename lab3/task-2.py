# Задание 2. Произведение N сомножителей.
print("=" * 60)
print("Задание 2. Произведение 1.1 · 1.2 · 1.3 · ...")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите количество сомножителей N (> 0): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0:
    print("Ошибка: N должно быть положительным.")
else:
    # Начинаем с 1, чтобы первый сомножитель не изменился при умножении.
    product = 1.0
    for i in range(1, n + 1):
        # На каждом шаге получаем следующий сомножитель: 1.1, 1.2, 1.3 и так далее.
        factor = 1 + i / 10
        product = product * factor
    print("Произведение:", product)
print("=" * 60)
