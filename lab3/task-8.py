# Задание 8. Наименьшее K с суммой от 1 до K не меньше N.
print("=" * 60)
print("Задание 8. Сумма 1 + 2 + ... + K не меньше N")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите целое число N (> 1): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 1:
    print("Ошибка: N должно быть больше 1.")
else:
    k = 0
    total = 0
    # Прибавляем следующее целое число, пока сумма меньше N.
    # При первом достижении N получаем самое маленькое подходящее K.
    while total < n:
        k = k + 1
        total = total + k
    print("Наименьшее K:", k)
    print("Сумма от 1 до K:", total)
print("=" * 60)
