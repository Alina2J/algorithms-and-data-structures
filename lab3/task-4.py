# Задание 4. Сумма степеней числа A.
print("=" * 60)
print("Задание 4. Сумма 1 + A + A^2 + ... + A^N")
print("\n--- ВВОД ДАННЫХ ---")
a = float(input("Введите число A: "))
n = int(input("Введите целое число N (> 0): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0:
    print("Ошибка: N должно быть положительным.")
else:
    # Первое слагаемое равно 1 — это A в нулевой степени.
    power = 1.0
    total = 1.0
    # В одном цикле получаем очередную степень и сразу прибавляем её к сумме.
    for i in range(1, n + 1):
        power = power * a
        total = total + power
    print("Сумма:", total)
print("=" * 60)
