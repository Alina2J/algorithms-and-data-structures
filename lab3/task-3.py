# Задание 3. Квадрат числа как сумма нечётных чисел.
print("=" * 60)
print("Задание 3. Квадрат числа как сумма нечётных чисел")
print("\n--- ВВОД ДАННЫХ ---")
n = int(input("Введите целое число N (> 0): "))

print("\n--- РЕЗУЛЬТАТ ---")
if n <= 0:
    print("Ошибка: N должно быть положительным.")
else:
    total = 0
    # Складываем первые N нечётных чисел: 1, 3, 5 и так далее.
    for i in range(1, n + 1):
        odd = 2 * i - 1
        total = total + odd
        # Показываем сумму после каждого прибавления, как требуется в задании.
        print(f"Добавили {odd}: текущая сумма = {total}")
    print(f"Квадрат числа {n} = {total}")
print("=" * 60)
